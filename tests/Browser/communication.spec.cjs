const { test, expect } = require('@playwright/test');
const { default: AxeBuilder } = require('@axe-core/playwright');
const { spawn, execFileSync } = require('node:child_process');
const { randomBytes } = require('node:crypto');
const net = require('node:net');
const path = require('node:path');
let base, token, server, env;
const root = path.resolve(__dirname, '../..');
const tool = path.join(root, 'tools/communication-browser.php');
const php = process.env.COR_TEST_PHP || 'php';
test.beforeAll(async () => {
  if (!/^cor_mgmt_test_/.test(process.env.COR_TEST_DB_NAME || '')) throw new Error('A guarded synthetic fixture is required.');
  const socket = net.createServer();
  await new Promise(resolve => socket.listen(0, '127.0.0.1', resolve));
  const port = socket.address().port;
  await new Promise(resolve => socket.close(resolve));
  base = `http://127.0.0.1:${port}`;
  token = randomBytes(32).toString('hex');
  env = { ...process.env, COR_TEST_BROWSER_TOKEN: token, COR_TEST_BROWSER_BASE: base, XDEBUG_MODE: 'off' };
  execFileSync(php, [tool, 'prepare'], { cwd: root, env, timeout: 90000 });
  server = spawn(php, ['-S', `127.0.0.1:${port}`, tool], { cwd: root, env, windowsHide: true, stdio: ['ignore', 'ignore', 'pipe'] });
  let error = '';
  server.stderr.on('data', data => { error += data.toString(); });
  const until = Date.now() + 30000;
  while (Date.now() < until) {
    try { const response = await fetch(base); if (response.status === 403) return; } catch { /* Server is starting. */ }
    if (server.exitCode !== null) throw new Error(error);
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  throw new Error('Synthetic browser server did not start.');
});
test.afterAll(async () => {
  if (server) { server.kill(); await new Promise(resolve => server.once('exit', resolve)); }
  if (env) execFileSync(php, [tool, 'cleanup'], { cwd: root, env, timeout: 90000 });
});
async function identity(context, actor) {
  await context.addCookies([{ name: 'cor_test_browser', value: token, url: base }, { name: 'cor_test_actor', value: actor, url: base }]);
  await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
}
async function axe(page) {
  const results = await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze();
  expect(results.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) }))).toEqual([]);
}

test('archive tools are restricted, readable by keyboard and require maintenance confirmations', async ({ page, context }) => {
  await identity(context, 'member');
  expect((await page.goto(base + '/archives')).status()).toBe(403);
  await expect(page.locator('[data-archive-form]')).toHaveCount(0);
  await identity(context, 'admin');
  await page.goto(base + '/archives');
  await expect(page.getByRole('heading', {name: 'Archives and storage transition', exact: true})).toBeVisible();
  await expect(page.getByRole('button', {name: 'Set up archive storage', exact: true})).toHaveCount(0);
  await expect(page.locator('input[name="backup"]')).not.toBeChecked();
  await expect(page.locator('input[name="quiesced"]')).not.toBeChecked();
  await page.getByRole('spinbutton', {name: 'Event ID', exact: true}).fill('880090');
  let posts = 0;
  page.on('request', request => { if (request.method() === 'POST') posts++; });
  const prepare = page.getByRole('button', {name: 'Prepare new race completion', exact: true});
  await prepare.click();
  expect(posts).toBe(0);
  expect(await page.locator('input[name="backup"]').evaluate(input => input.validity.valueMissing)).toBe(true);
  await page.getByLabel('A verified backup is available.', {exact: true}).focus();
  await page.keyboard.press('Space');
  await expect(page.locator('input[name="backup"]')).toBeChecked();
  await prepare.click();
  expect(posts).toBe(0);
  expect(await page.locator('input[name="quiesced"]').evaluate(input => input.validity.valueMissing)).toBe(true);
  await page.getByLabel('All source writers are stopped.', {exact: true}).focus();
  await page.keyboard.press('Space');
  await expect(page.locator('input[name="quiesced"]')).toBeChecked();
  await axe(page);
});

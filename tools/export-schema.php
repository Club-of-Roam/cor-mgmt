<?php
/** Emit a reviewable reference without bootstrapping WordPress or opening a database. */
declare(strict_types=1);
require dirname(__DIR__).'/vendor/autoload.php';
use Cor\Mgmt\Infrastructure\WordPress\Schema\Catalogue;
$module = in_array('--participation', $argv, true);
$results = in_array('--results', $argv, true);
$donations = in_array('--donations', $argv, true);
$queue = in_array('--mail-queue', $argv, true);
$communication = in_array('--communication', $argv, true);
$definitions = $module ? \Cor\Mgmt\Infrastructure\WordPress\Schema\ParticipationSchema::definitions() : Catalogue::legacy()+Catalogue::shadow();
if ($results) { $definitions = \Cor\Mgmt\Infrastructure\WordPress\Schema\ResultsSchema::definitions(); }
if ($communication) { $definitions = \Cor\Mgmt\Infrastructure\WordPress\Schema\CommunicationSchema::definitions(); }
if ($donations) { $definitions = \Cor\Mgmt\Infrastructure\WordPress\Schema\DonationSchema::definitions(); }
if ($queue) { $definitions = \Cor\Mgmt\Infrastructure\WordPress\Schema\MailQueueSchema::definitions(); }
$quote=static fn(string $identifier): string=>'`'.str_replace('`','``',$identifier).'`';
$sql="-- Generated by php tools/export-schema.php --write; do not edit by hand.\n";
$sql.="-- Storage schema ".($queue ? \Cor\Mgmt\Infrastructure\WordPress\Schema\MailQueueSchema::VERSION : ($communication ? \Cor\Mgmt\Infrastructure\WordPress\Schema\CommunicationSchema::VERSION : ($donations ? \Cor\Mgmt\Infrastructure\WordPress\Schema\DonationSchema::VERSION : ($results ? \Cor\Mgmt\Infrastructure\WordPress\Schema\ResultsSchema::VERSION : ($module ? \Cor\Mgmt\Infrastructure\WordPress\Schema\ParticipationSchema::VERSION : Catalogue::STORAGE_VERSION)))))."; {prefix} denotes the WordPress table prefix.\n";
$sql.="-- Reference only: the installer checks ownership, resumability and existing data.\n\n";
foreach ($definitions as $suffix=>$definition) {
    $parts=[];
    foreach ($definition['columns'] as $name=>$type) { $parts[]='    '.$quote($name).' '.$type; }
    foreach ($definition['indexes'] as $name=>$fields) {
        $parts[]='    '.($name==='PRIMARY'?'PRIMARY KEY':(str_starts_with($name,'UNIQUE_') ? 'UNIQUE KEY ' : 'KEY ').$quote($name)).' ('.implode(',',array_map($quote,$fields)).')';
    }
    $sql.='CREATE TABLE '.$quote('{prefix}'.$suffix)." (\n".implode(",\n",$parts)."\n) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci COMMENT='".Catalogue::OWNER."';\n\n";
}
$target= $queue ? dirname(__DIR__).'/docs/schema-mail-queue-1.0.0.sql' : dirname(__DIR__).($communication ? '/docs/schema-communication-1.0.0.sql' : ($donations ? '/docs/schema-donations-1.0.0.sql' : ($results ? '/docs/schema-results-1.0.0.sql' : ($module ? '/docs/schema-participation-1.0.0.sql' : '/docs/schema-3.0.0.sql'))));
if (in_array('--write',$argv,true)) { file_put_contents($target,$sql); echo "Schema reference written.\n"; }
elseif (in_array('--check',$argv,true)) {
    if (!is_file($target) || str_replace("\r\n","\n",file_get_contents($target))!==$sql) { fwrite(STDERR,"Stale schema reference; run php tools/export-schema.php --write.\n"); exit(1); }
    echo "Schema reference matches catalogue.\n";
} else { echo $sql; }

<?php
/** Emit a reviewable reference without bootstrapping WordPress or opening a database. */
declare(strict_types=1);
require dirname(__DIR__).'/vendor/autoload.php';
use Cor\Mgmt\Infrastructure\WordPress\Schema\Catalogue;
$quote=static fn(string $identifier): string=>'`'.str_replace('`','``',$identifier).'`';
$sql="-- Generated by php tools/export-schema.php --write; do not edit by hand.\n";
$sql.="-- Storage schema ".Catalogue::STORAGE_VERSION."; {prefix} denotes the WordPress table prefix.\n";
$sql.="-- Reference only: the installer checks ownership, resumability and existing data.\n\n";
foreach (Catalogue::legacy()+Catalogue::shadow() as $suffix=>$definition) {
    $parts=[];
    foreach ($definition['columns'] as $name=>$type) { $parts[]='    '.$quote($name).' '.$type; }
    foreach ($definition['indexes'] as $name=>$fields) {
        $parts[]='    '.($name==='PRIMARY'?'PRIMARY KEY':'KEY '.$quote($name)).' ('.implode(',',array_map($quote,$fields)).')';
    }
    $sql.='CREATE TABLE '.$quote('{prefix}'.$suffix)." (\n".implode(",\n",$parts)."\n) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci COMMENT='".Catalogue::OWNER."';\n\n";
}
$target=dirname(__DIR__).'/docs/schema-3.0.0.sql';
if (in_array('--write',$argv,true)) { file_put_contents($target,$sql); echo "Schema reference written.\n"; }
elseif (in_array('--check',$argv,true)) {
    if (!is_file($target) || str_replace("\r\n","\n",file_get_contents($target))!==$sql) { fwrite(STDERR,"Stale schema reference; run php tools/export-schema.php --write.\n"); exit(1); }
    echo "Schema reference matches catalogue.\n";
} else { echo $sql; }
